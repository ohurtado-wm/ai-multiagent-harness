#!/usr/bin/env node
// Generates (or checks with --check) the plan status in docs/status/plans.md from the header of each
// plan in docs/plans/**. That way there is a single source: the plan itself.
//
// Header of each plan (first lines of the file; everything except `status` is optional):
//   ---
//   status: draft | approved | in-progress | in-validation | closed
//   parent: PLAN_OF_THE_PARENT.md      (file name, unique in docs/plans/)
//   previous: PLAN_PREVIOUS.md
//   next: PLAN_NEXT.md                 (or free text if it has no plan yet)
//   issue: 123                         (number of the plan's GitHub issue)
//   ---
// The children of a plan are not written: they come from `parent`. Their order comes from the previous/next chain.
//
// Usage: node scripts/plan-status.mjs [--check | --summary | --plan <file or part of the name>]
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const STATUSES = ["draft", "approved", "in-progress", "in-validation", "closed"];
export const ACTIVE = ["in-progress", "in-validation"];
export const START = "<!-- plans:start (generated by scripts/plan-status.mjs; do not edit by hand) -->";
export const END = "<!-- plans:end -->";

function* files(dir) {
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) yield* files(path);
    else if (name.endsWith(".md")) yield path;
  }
}

const unquote = (v) => v?.trim().replace(/^["'](.*)["']$/, "$1") || undefined;

// Returns { status, title, parent, previous, next, issue } of a plan; missing keys stay undefined.
export function readPlan(text) {
  const header = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/)?.[1] ?? "";
  const key = (k) => unquote(header.match(new RegExp(`^${k}:\\s*(.+?)\\s*$`, "m"))?.[1]);
  const title = text.match(/^# (.+)$/m)?.[1].trim() ?? "(untitled)";
  return { status: key("status"), title, parent: key("parent"), previous: key("previous"), next: key("next"), issue: key("issue") };
}

// Title without the prefix every plan repeats.
export const short = (title) => title.replace(/^Plan( —|:)\s*/, "");

const isFile = (v) => typeof v === "string" && v.endsWith(".md");

// Reads every plan and validates its header. Returns { plans: Map<file, plan>, errors }.
export function loadPlans(root) {
  const errors = [];
  const plans = new Map();
  for (const path of files(join(root, "docs/plans"))) {
    const rel = relative(root, path).split("\\").join("/");
    const file = basename(path);
    const plan = { file, rel, link: relative(join(root, "docs/status"), path).split("\\").join("/"), ...readPlan(readFileSync(path, "utf8")) };
    if (plans.has(file)) errors.push(`${rel}: the name «${file}» is repeated (${plans.get(file).rel}); plans are named by file and the name must be unique.`);
    plans.set(file, plan);
    if (!plan.status) errors.push(`${rel}: the «status:» header is missing (${STATUSES.join(" | ")}).`);
    else if (!STATUSES.includes(plan.status)) errors.push(`${rel}: status «${plan.status}» is not valid (${STATUSES.join(" | ")}).`);
    if (plan.issue !== undefined && !/^[1-9]\d*$/.test(plan.issue)) errors.push(`${rel}: «issue: ${plan.issue}» must be only the GitHub issue number (no «#» or URL).`);
  }
  for (const p of plans.values()) {
    for (const k of ["parent", "previous"]) {
      if (p[k] && !plans.has(p[k])) errors.push(`${p.rel}: «${k}: ${p[k]}» is not a plan in docs/plans/.`);
    }
    if (isFile(p.next) && !plans.has(p.next)) errors.push(`${p.rel}: «next: ${p.next}» is not a plan in docs/plans/ (if it has no plan yet, write it as text without .md).`);
    if (p.parent === p.file || p.previous === p.file || p.next === p.file) errors.push(`${p.rel}: it names itself.`);
    const nxt = plans.get(p.next);
    if (nxt && nxt.previous !== p.file) errors.push(`${p.rel}: says «next: ${nxt.file}», but ${nxt.file} does not say «previous: ${p.file}».`);
    const prv = plans.get(p.previous);
    if (prv && prv.next !== p.file) errors.push(`${p.rel}: says «previous: ${prv.file}», but ${prv.file} does not say «next: ${p.file}».`);
    const seen = new Set([p.file]);
    for (let q = plans.get(p.parent); q; q = plans.get(q.parent)) {
      if (seen.has(q.file)) {
        errors.push(`${p.rel}: the «parent» chain forms a cycle.`);
        break;
      }
      seen.add(q.file);
    }
  }
  return { plans, errors };
}

// Children of a plan (or roots with null), in order: first the previous→next chains, then the loose ones.
export function children(plans, parent) {
  const group = [...plans.values()].filter((p) => (p.parent ?? null) === parent);
  const names = new Set(group.map((p) => p.file));
  const order = [];
  const seen = new Set();
  const heads = group.filter((p) => !names.has(p.previous) && names.has(p.next));
  for (const head of heads) {
    for (let p = head; p && names.has(p.file) && !seen.has(p.file); p = plans.get(p.next)) {
      seen.add(p.file);
      order.push(p);
    }
  }
  for (const p of group) if (!seen.has(p.file)) order.push(p);
  return order;
}

const link = (p) => `[${short(p.title).replaceAll("|", "\\|").replaceAll("[", "\\[").replaceAll("]", "\\]")}](${p.link})`;
const target = (plans, value) => (plans.has(value) ? link(plans.get(value)) : value);

// Every plan in tree order (parent before children, siblings in their order).
export function inOrder(plans) {
  const order = [];
  const seen = new Set();
  const visit = (parent) => {
    for (const p of children(plans, parent)) {
      if (seen.has(p.file)) continue;
      seen.add(p.file);
      order.push(p);
      visit(p.file);
    }
  };
  visit(null);
  return order;
}

// Plans in progress that have no child in progress: what is really being built.
const inProgressLeaves = (plans, all) => all.filter((p) => p.status === "in-progress" && !children(plans, p.file).some((c) => c.status === "in-progress"));

// «Now» summary: in progress, waiting for the owner (by parent) and what comes next.
export function summary(plans) {
  const all = inOrder(plans);
  const lines = ["### Now", "", "**In progress** (being built):", ""];
  const progress = inProgressLeaves(plans, all);
  for (const p of progress) {
    const extra = [p.parent && `of ${link(plans.get(p.parent))}`, p.next && `next: ${target(plans, p.next)}`].filter(Boolean);
    lines.push(`- ${link(p)}${extra.length ? ` — ${extra.join("; ")}` : ""}`);
  }
  if (!progress.length) lines.push("- Nothing.");
  lines.push("", "**Waiting for the owner** (`in-validation`: implemented; it still needs validation, a remote rollout or an owner step):", "");
  const byParent = new Map();
  for (const p of all.filter((x) => x.status === "in-validation")) {
    const k = p.parent ?? "";
    byParent.set(k, [...(byParent.get(k) ?? []), p]);
  }
  for (const [parent, list] of byParent) {
    const name = parent ? link(plans.get(parent)) : "No parent";
    lines.push(`- ${name}: ${list.map(link).join(", ")}`);
  }
  if (!byParent.size) lines.push("- Nothing.");
  lines.push("", "**What comes next:**", "");
  const nexts = [];
  for (const p of all.filter((x) => ACTIVE.includes(x.status) && x.next)) {
    const s = plans.get(p.next);
    if (!s || (!ACTIVE.includes(s.status) && s.status !== "closed")) nexts.push(`- After ${link(p)}: ${target(plans, p.next)}${s ? ` (${s.status})` : ""}`);
  }
  const listed = new Set(all.filter((x) => ACTIVE.includes(x.status)).map((x) => x.next));
  for (const p of all.filter((x) => (x.status === "draft" || x.status === "approved") && !listed.has(x.file))) {
    nexts.push(`- ${link(p)} (${p.status}${p.parent ? `, of ${link(plans.get(p.parent))}` : ""})`);
  }
  lines.push(...(nexts.length ? nexts : ["- Nothing pending a plan."]));
  return lines.join("\n");
}

// Tree of every plan, nested by parent.
export function tree(plans) {
  const lines = ["### Plan tree", "", "Nested by `parent`; siblings follow the `previous`/`next` order and loose ones (improvements, adjustments) go last.", ""];
  const level = (p) => {
    let n = 0;
    for (let x = plans.get(p.parent); x && n < plans.size; x = plans.get(x.parent)) n++;
    return n;
  };
  for (const p of inOrder(plans)) lines.push(`${"  ".repeat(level(p))}- ${link(p)} · ${p.status ?? "—"}`);
  return lines.join("\n");
}

// Returns { table, errors } with the whole generated block (between the markers).
export function generateTable(root) {
  const { plans, errors } = loadPlans(root);
  const table = [START, "", summary(plans), "", tree(plans), "", END].join("\n");
  return { table, errors };
}

// Replaces the block between markers; returns null if the markers are missing.
export function applyTable(document, table) {
  const i = document.indexOf(START);
  const j = document.indexOf(END);
  if (i < 0 || j < 0 || j < i) return null;
  return document.slice(0, i) + table + document.slice(j + END.length);
}

const label = (plans, v) => (plans.has(v) ? `${v} (${plans.get(v).status})` : v);

// Text card of a plan: status, parent chain, previous, next and children.
export function card(plans, query) {
  const q = query.toLowerCase();
  const exact = plans.get(query);
  const found = exact ? [exact] : [...plans.values()].filter((p) => p.file.toLowerCase().includes(q) || p.title.toLowerCase().includes(q));
  if (!found.length) return `No plan matches «${query}».`;
  if (found.length > 1) return [`Several plans match «${query}»:`, ...found.map((p) => `- ${p.file} (${p.status})`)].join("\n");
  const p = found[0];
  const parents = [];
  for (let x = plans.get(p.parent); x && !parents.includes(x.file); x = plans.get(x.parent)) parents.unshift(x.file);
  const list = children(plans, p.file);
  return [
    `${p.title}`,
    `file: ${p.rel}`,
    `status: ${p.status}`,
    `parents: ${parents.length ? parents.map((a) => label(plans, a)).join(" > ") : "—"}`,
    `previous: ${p.previous ? label(plans, p.previous) : "—"}`,
    `next: ${p.next ? label(plans, p.next) : "—"}`,
    `children: ${list.length ? "" : "—"}`,
    ...list.map((c) => `  - ${c.file} (${c.status})`),
  ].join("\n");
}

// Short plain-text summary (for the session start hook).
export function summaryText(plans) {
  const all = inOrder(plans);
  const name = (p) => `${short(p.title)} (${p.file})`;
  const lines = [];
  const progress = inProgressLeaves(plans, all);
  if (progress.length) lines.push(`Plans in progress: ${progress.map(name).join("; ")}.`);
  const validation = all.filter((p) => p.status === "in-validation");
  if (validation.length) {
    const count = new Map();
    for (const p of validation) {
      const k = p.parent ? short(plans.get(p.parent).title) : "no parent";
      count.set(k, (count.get(k) ?? 0) + 1);
    }
    lines.push(`Waiting for the owner (in-validation): ${validation.length} plan(s) — ${[...count].map(([k, n]) => `${k}: ${n}`).join("; ")}.`);
  }
  const nexts = all
    .filter((p) => ACTIVE.includes(p.status) && p.next && !(plans.get(p.next) && ["in-progress", "in-validation", "closed"].includes(plans.get(p.next).status)))
    .map((p) => (plans.has(p.next) ? name(plans.get(p.next)) : p.next));
  if (nexts.length) lines.push(`What comes next: ${[...new Set(nexts)].join("; ")}.`);
  lines.push("Detail: docs/status/plans.md («Now» section and tree) or node scripts/plan-status.mjs --plan <file>.");
  return lines.join("\n");
}

function main() {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const args = process.argv.slice(2);
  if (args[0] === "--plan" || args[0] === "--summary") {
    const { plans } = loadPlans(root);
    console.log(args[0] === "--plan" ? card(plans, args[1] ?? "") : summaryText(plans));
    return;
  }
  const statusPath = join(root, "docs/status/plans.md");
  const { table, errors } = generateTable(root);
  if (errors.length) {
    console.error(errors.join("\n"));
    process.exit(1);
  }
  const current = readFileSync(statusPath, "utf8");
  const updated = applyTable(current, table);
  if (updated === null) {
    console.error("The plans table markers are missing in docs/status/plans.md.");
    process.exit(1);
  }
  if (args.includes("--check")) {
    if (updated !== current) {
      console.error("The plan status in docs/status/plans.md is stale: run `node scripts/plan-status.mjs`.");
      process.exit(1);
    }
    console.log("Plan status up to date.");
  } else {
    writeFileSync(statusPath, updated);
    console.log("Plan status updated.");
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) main();
